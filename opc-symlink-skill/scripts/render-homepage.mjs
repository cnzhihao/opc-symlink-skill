#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import {
  escapeHtml,
  labelsFor,
  localizedRawMetadata,
  localeKey,
  normalizeMetadata,
  normalizeTemplateName,
} from './lib/html.mjs';
import { renderBuilderOs } from './templates/builder-os.mjs';
import { renderProductLed } from './templates/product-led.mjs';
import { renderProofFirst } from './templates/proof-first.mjs';

const templates = {
  'product-led': renderProductLed,
  'builder-os': renderBuilderOs,
  'proof-first': renderProofFirst,
};

function parseArgs(argv) {
  const positional = [];
  let template = '';

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];

    if (arg === '--template' || arg === '-t') {
      template = argv[index + 1] || '';
      index += 1;
      continue;
    }

    if (arg.startsWith('--template=')) {
      template = arg.split('=').slice(1).join('=');
      continue;
    }

    if (!arg.startsWith('-')) {
      positional.push(arg);
    }
  }

  return {
    inputPath: positional[0],
    outputPath: positional[1] || 'personal-homepage.html',
    template,
  };
}

const { inputPath, outputPath, template } = parseArgs(process.argv.slice(2));

if (!inputPath) {
  console.error(
    'Usage: node render-homepage.mjs metadata.json [output.html] --template product-led|builder-os|proof-first',
  );
  process.exit(1);
}

const rawMetadata = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
const localizedInputs = localizedRawMetadata(rawMetadata);
const localizedMetadata = localizedInputs.map((item) => {
  return normalizeMetadata(item.raw);
});
const selectedTemplate = normalizeTemplateName(
  template || localizedMetadata[0]?.style.template,
);

if (!selectedTemplate) {
  console.error(
    'Missing template. Choose --template product-led, --template builder-os, --template proof-first, or set style.template in metadata.',
  );
  process.exit(1);
}

const render = templates[selectedTemplate];

if (!render) {
  console.error(
    `Unknown template "${selectedTemplate}". Expected product-led, builder-os, or proof-first.`,
  );
  process.exit(1);
}

function extractTag(html, tagName) {
  const match = html.match(
    new RegExp(`<${tagName}[^>]*>([\\s\\S]*?)<\\/${tagName}>`, 'i'),
  );
  return match ? match[1] : '';
}

function extractMetaDescription(html) {
  const match = html.match(
    /<meta\s+name="description"\s+content="([^"]*)"\s*>/i,
  );
  return match ? match[1] : '';
}

function languageName(locale) {
  return localeKey(locale) === 'zh' ? '中文' : 'English';
}

function renderMultilingualHtml(pages) {
  const first = pages[0];
  const firstHtml = first.html;
  const style = extractTag(firstHtml, 'style');
  const title = extractTag(firstHtml, 'title');
  const description = extractMetaDescription(firstHtml);
  const jsonLd = extractTag(firstHtml, 'script');
  const buttons = pages
    .map((page, index) => {
      return `<button class="language-button" type="button" data-locale="${escapeHtml(page.locale)}" aria-pressed="${index === 0 ? 'true' : 'false'}">${escapeHtml(languageName(page.locale))}</button>`;
    })
    .join('');
  const bodies = pages
    .map((page, index) => {
      return `<div class="localized-page" data-locale="${escapeHtml(page.locale)}"${index === 0 ? '' : ' hidden'}>${extractTag(page.html, 'body')}</div>`;
    })
    .join('');

  return `<!doctype html>
<!--
  Generated by opc-symlink-skill/scripts/render-homepage.mjs.
  Do not edit this HTML directly. Update the metadata JSON and rerun the renderer.
-->
<html lang="${escapeHtml(first.locale || 'en')}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${title}</title>
  <meta name="description" content="${description}">
  <style>${style}
.language-switcher {
  position: fixed;
  right: 16px;
  top: 16px;
  z-index: 20;
  display: flex;
  gap: 8px;
}
.language-button {
  min-height: 36px;
  border-radius: 999px;
  border: 1px solid var(--line, #e5e7eb);
  background: var(--paper, #ffffff);
  color: var(--ink, #111827);
  font: inherit;
  font-size: 13px;
  font-weight: 800;
  padding: 0 12px;
}
.language-button[aria-pressed="true"] {
  background: var(--accent, #2563eb);
  border-color: var(--accent, #2563eb);
  color: #fff;
}
.localized-page[hidden] { display: none !important; }
  </style>
  <script type="application/ld+json">${jsonLd}</script>
</head>
<body>
  <nav class="language-switcher" aria-label="Language">${buttons}</nav>
  ${bodies}
  <script>
    (() => {
      const pages = [...document.querySelectorAll('.localized-page')];
      const buttons = [...document.querySelectorAll('.language-button')];
      const available = pages.map((page) => page.dataset.locale);
      const stored = localStorage.getItem('opc-symlink-locale');
      const browser = navigator.language || '';
      const initial = available.includes(stored)
        ? stored
        : available.find((locale) => browser.toLowerCase().startsWith(locale.toLowerCase().slice(0, 2))) || available[0];

      function setLocale(locale) {
        pages.forEach((page) => {
          page.hidden = page.dataset.locale !== locale;
        });
        buttons.forEach((button) => {
          button.setAttribute('aria-pressed', String(button.dataset.locale === locale));
        });
        document.documentElement.lang = locale;
        localStorage.setItem('opc-symlink-locale', locale);
      }

      buttons.forEach((button) => {
        button.addEventListener('click', () => setLocale(button.dataset.locale));
      });
      setLocale(initial);
    })();
  </script>
</body>
</html>
`;
}

const renderedPages = localizedMetadata.map((metadata) => {
  return {
    locale: metadata.locale,
    html: render(metadata),
  };
});
const html =
  renderedPages.length > 1
    ? renderMultilingualHtml(renderedPages)
    : renderedPages[0].html;
const resolvedOutput = path.resolve(outputPath);
const resolvedInput = path.resolve(inputPath);

if (resolvedInput === resolvedOutput) {
  console.error(
    'Refusing to overwrite input metadata. Use separate metadata JSON and output HTML paths.',
  );
  process.exit(1);
}

fs.writeFileSync(resolvedOutput, html);
console.log(resolvedOutput);
