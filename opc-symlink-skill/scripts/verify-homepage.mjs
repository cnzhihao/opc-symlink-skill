#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { escapeHtml } from './lib/html.mjs';

const marker = 'Generated by opc-symlink-skill/scripts/render-homepage.mjs';

function parseArgs(argv) {
  const positional = [];
  let allowSingleLanguage = false;
  let allowMultipleHtml = false;

  for (const arg of argv) {
    if (arg === '--single-language') {
      allowSingleLanguage = true;
      continue;
    }

    if (arg === '--allow-multiple-html') {
      allowMultipleHtml = true;
      continue;
    }

    if (!arg.startsWith('-')) {
      positional.push(arg);
    }
  }

  let metadataPath = positional[0];
  let htmlPath = positional[1];

  if (
    metadataPath?.toLowerCase().endsWith('.html') &&
    htmlPath?.toLowerCase().endsWith('.json')
  ) {
    [metadataPath, htmlPath] = [htmlPath, metadataPath];
  }

  return {
    metadataPath,
    htmlPath,
    allowSingleLanguage,
    allowMultipleHtml,
  };
}

function fail(message) {
  console.error(`Verification failed: ${message}`);
  process.exit(1);
}

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (error) {
    fail(`could not read metadata JSON at ${filePath}: ${error.message}`);
  }
}

function collectStrings(value, results = []) {
  if (typeof value === 'string') {
    const trimmed = value.trim();

    if (trimmed) {
      results.push(trimmed);
    }

    return results;
  }

  if (Array.isArray(value)) {
    value.forEach((item) => collectStrings(item, results));
    return results;
  }

  if (value && typeof value === 'object') {
    Object.values(value).forEach((item) => collectStrings(item, results));
  }

  return results;
}

function unique(values) {
  return [...new Set(values)];
}

function privacyBlocksFrom(metadata) {
  const blocks = [];

  if (metadata.privacy) {
    blocks.push(metadata.privacy);
  }

  for (const locales of [metadata.locales, metadata.localizations]) {
    if (!locales || typeof locales !== 'object') {
      continue;
    }

    Object.values(locales).forEach((localized) => {
      if (localized?.privacy) {
        blocks.push(localized.privacy);
      }
    });
  }

  return blocks;
}

const {
  metadataPath,
  htmlPath,
  allowSingleLanguage,
  allowMultipleHtml,
} = parseArgs(process.argv.slice(2));

if (!metadataPath || !htmlPath) {
  console.error(
    'Usage: node verify-homepage.mjs metadata.json homepage.html [--single-language] [--allow-multiple-html]',
  );
  process.exit(1);
}

const resolvedMetadata = path.resolve(metadataPath);
const resolvedHtml = path.resolve(htmlPath);

if (!fs.existsSync(resolvedMetadata)) {
  fail(`metadata file does not exist: ${resolvedMetadata}`);
}

if (!fs.existsSync(resolvedHtml)) {
  fail(`HTML file does not exist: ${resolvedHtml}`);
}

if (resolvedMetadata === resolvedHtml) {
  fail('metadata JSON and output HTML must be separate files');
}

const metadata = readJson(resolvedMetadata);
const html = fs.readFileSync(resolvedHtml, 'utf8');
const hasBilingualMetadata = Boolean(
  metadata.locales && metadata.locales['zh-CN'] && metadata.locales.en,
);

if (!html.includes(marker)) {
  fail(
    'HTML does not contain the renderer marker. Recreate it with scripts/render-homepage.mjs instead of hand-editing HTML.',
  );
}

if (!hasBilingualMetadata && !allowSingleLanguage) {
  fail(
    'bilingual metadata is required by default. Add locales.zh-CN and locales.en, or pass --single-language only when the user explicitly requested one language.',
  );
}

if (hasBilingualMetadata) {
  const requiredFragments = [
    'language-switcher',
    'data-locale="zh-CN"',
    'data-locale="en"',
  ];
  const missingFragments = requiredFragments.filter(
    (fragment) => !html.includes(fragment),
  );

  if (missingFragments.length) {
    fail(
      `bilingual metadata exists, but generated HTML is missing: ${missingFragments.join(', ')}`,
    );
  }
}

const privateStrings = unique(
  privacyBlocksFrom(metadata)
    .flatMap((privacy) => {
      return collectStrings(privacy.exclude).concat(
        collectStrings(privacy.approvalNotes),
      );
    })
    .filter((item) => item.length >= 2),
);
const leaked = privateStrings.filter((item) => {
  return html.includes(item) || html.includes(escapeHtml(item));
});

if (leaked.length) {
  fail(
    `HTML contains privacy metadata that must not render: ${leaked
      .slice(0, 5)
      .join(', ')}`,
  );
}

if (!allowMultipleHtml) {
  const htmlDir = path.dirname(resolvedHtml);
  const generatedHtmlFiles = fs
    .readdirSync(htmlDir)
    .filter((fileName) => fileName.toLowerCase().endsWith('.html'))
    .map((fileName) => path.join(htmlDir, fileName))
    .filter((candidate) => {
      try {
        return fs.readFileSync(candidate, 'utf8').includes(marker);
      } catch {
        return false;
      }
    });

  if (generatedHtmlFiles.length > 1) {
    fail(
      `expected one generated homepage HTML in ${htmlDir}, found ${generatedHtmlFiles
        .map((fileName) => path.basename(fileName))
        .join(', ')}. Reuse one output path or pass --allow-multiple-html only for explicit multiple deliverables.`,
    );
  }
}

console.log(`Verified ${resolvedHtml}`);
